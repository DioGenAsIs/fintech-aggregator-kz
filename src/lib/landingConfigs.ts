export function getLandingConfig(locale: Locale, slug: string) {
  return landingPageConfigs.find((config) => config.locale === locale && config.slug === slug);
}

export function getLocaleLandingConfigs(locale: Locale) {
  return landingPageConfigs.filter((config) => config.locale === locale);
}

export function getAlternateLocaleConfig(config: LandingPageSeoConfig) {
  return landingPageConfigs.find(
    (candidate) => candidate.key === config.key && candidate.locale !== config.locale,
  );
}
